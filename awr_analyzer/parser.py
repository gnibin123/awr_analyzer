"""Parses an Oracle AWR (Automatic Workload Repository) HTML report into the
structured :class:`~awr_analyzer.models.AWRReport` object used by the rest of
the tool.

AWR HTML reports are generated by ``awrrpt.sql`` / ``awrrpti.sql`` and their
exact markup varies a bit across Oracle versions (10g through 19c/21c), so
this parser avoids relying on fixed anchor names or CSS classes. Instead it:

1. Finds every ``<table>`` in the document.
2. Figures out which "section" a table belongs to by looking at the nearest
   preceding text in the document (the section heading Oracle prints just
   above each table), matched with heuristics/regexes.
3. Parses the table's rows using the table's own header row to figure out
   which column is which, so it degrades gracefully when Oracle renames or
   reorders columns between versions.

Sections that aren't recognized are simply skipped (and recorded in
``raw_section_titles`` for troubleshooting) rather than raising an error, so
a partially-recognized report still produces useful output.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Optional

from bs4 import BeautifulSoup, NavigableString, Tag

from .models import AWRReport, SnapshotInfo, SQLStat, TablespaceIOStat, WaitEvent

_SQL_ID_RE = re.compile(r"^[A-Za-z0-9/+]{13}$")


def _to_float(text: Optional[str]):
    """Best-effort conversion of an AWR table cell into a float."""
    if text is None:
        return None
    text = text.strip().replace("\xa0", " ").strip()
    if text in ("", "-", "N/A", "n/a"):
        return None
    negative = text.startswith("(") and text.endswith(")")
    text = text.strip("()")
    text = text.replace(",", "").replace("%", "").strip()
    try:
        value = float(text)
    except ValueError:
        return None
    return -value if negative else value


def _norm(text: Optional[str]) -> str:
    if not text:
        return ""
    text = text.replace("\xa0", " ")
    text = re.sub(r"\s+", " ", text).strip()
    return text


def _key(text: str) -> str:
    text = _norm(text).lower()
    text = re.sub(r"[():%]", "", text)
    text = re.sub(r"[\s/.-]+", "_", text).strip("_")
    return text


def _row_cells(row: Tag):
    return [_norm(c.get_text(" ")) for c in row.find_all(["td", "th"])]


def _nearby_heading_text(table: Tag, max_chars: int = 400) -> str:
    """Collects the text that appears just before ``table`` in document
    order, stopping once we've walked back past the previous table (so we
    don't pick up an earlier section's trailing content)."""
    parts = []
    total_len = 0
    for el in table.previous_elements:
        if isinstance(el, Tag) and el.name == "table":
            break
        if isinstance(el, NavigableString):
            text = str(el).strip()
            if text:
                parts.append(text)
                total_len += len(text)
        if total_len >= max_chars:
            break
    parts.reverse()
    return _norm(" ".join(parts))


# Ordered so the more specific patterns are tried before generic ones.
_SECTION_PATTERNS = [
    ("sql_elapsed", re.compile(r"sql ordered by elapsed time", re.I)),
    ("sql_cpu", re.compile(r"sql ordered by cpu time", re.I)),
    ("sql_gets", re.compile(r"sql ordered by gets", re.I)),
    ("sql_reads", re.compile(r"sql ordered by reads", re.I)),
    ("sql_executions", re.compile(r"sql ordered by executions", re.I)),
    ("tablespace_io", re.compile(r"tablespace io stats", re.I)),
    ("undo", re.compile(r"undo segment", re.I)),
    ("wait_class", re.compile(r"wait classes? by total wait time", re.I)),
    ("top_wait_events", re.compile(
        r"top \d+ timed (foreground )?events|foreground wait events|top timed events", re.I)),
    ("time_model", re.compile(r"time model statistics", re.I)),
    ("host_cpu", re.compile(r"^host cpu", re.I)),
    ("instance_cpu", re.compile(r"^instance cpu", re.I)),
    ("instance_efficiency", re.compile(r"instance efficiency", re.I)),
    ("load_profile", re.compile(r"load profile", re.I)),
]


def _classify_table(table: Tag) -> Optional[str]:
    heading = _nearby_heading_text(table)
    best_key = None
    best_pos = -1
    for key, pattern in _SECTION_PATTERNS:
        m = None
        for m in pattern.finditer(heading):
            pass
        if m and m.end() > best_pos:
            best_pos = m.end()
            best_key = key
    return best_key


def _header_index(headers: list, *patterns: str) -> Optional[int]:
    for i, h in enumerate(headers):
        for p in patterns:
            if re.search(p, h, re.I):
                return i
    return None


class AWRParseError(Exception):
    pass


def parse_awr_html(html: str, source_path: Optional[str] = None) -> AWRReport:
    soup = BeautifulSoup(html, "lxml")
    report = AWRReport(source_path=source_path)

    _parse_header_info(soup, report)

    for table in soup.find_all("table"):
        section = _classify_table(table)
        rows = table.find_all("tr")
        if not rows:
            continue
        heading = _nearby_heading_text(table)
        if heading:
            report.raw_section_titles.append(heading[:120])

        if section == "load_profile":
            _parse_load_profile(table, report)
        elif section == "instance_efficiency":
            _parse_instance_efficiency(table, report)
        elif section == "top_wait_events":
            _parse_wait_events(table, report.top_wait_events)
        elif section == "wait_class":
            _parse_wait_events(table, report.wait_class_stats, class_col_is_name=True)
        elif section == "time_model":
            _parse_time_model(table, report)
        elif section == "host_cpu":
            _parse_kv_table(table, report.host_cpu)
        elif section == "instance_cpu":
            _parse_kv_table(table, report.instance_cpu)
        elif section in ("sql_elapsed", "sql_cpu", "sql_gets", "sql_reads", "sql_executions"):
            target = {
                "sql_elapsed": report.sql_by_elapsed,
                "sql_cpu": report.sql_by_cpu,
                "sql_gets": report.sql_by_gets,
                "sql_reads": report.sql_by_reads,
                "sql_executions": report.sql_by_executions,
            }[section]
            _parse_sql_table(table, target)
        elif section == "tablespace_io":
            _parse_tablespace_io(table, report.tablespace_io)
        elif section == "undo":
            _parse_kv_table(table, report.undo_stats)

    return report


def parse_awr_file(path: str) -> AWRReport:
    p = Path(path)
    html = p.read_text(encoding="utf-8", errors="replace")
    return parse_awr_html(html, source_path=str(p))


