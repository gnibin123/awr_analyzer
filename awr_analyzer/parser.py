def _parse_header_info(soup: BeautifulSoup, report: AWRReport) -> None:
    info = report.info
    full_text = soup.get_text("\n")

    def find(pattern):
        m = re.search(pattern, full_text, re.I)
        return _norm(m.group(1)) if m else None

    info.elapsed_minutes = _to_float(find(r"Elapsed:\s*([\d,.\s]+)\(?\s*mins"))
    info.db_time_minutes = _to_float(find(r"DB Time:\s*([\d,.\s]+)\(?\s*mins"))

    for table in soup.find_all("table"):
        headers = [ _key(c) for c in _row_cells(table.find("tr")) ] if table.find("tr") else []
        joined = " ".join(headers)
        if {"db_name", "db_id", "instance"} <= set(headers) or ("db_name" in joined and "instance" in joined):
            data_row = table.find_all("tr")[1] if len(table.find_all("tr")) > 1 else None
            if data_row:
                cells = _row_cells(data_row)
                mapping = dict(zip(headers, cells))
                info.db_name = mapping.get("db_name") or info.db_name
                info.db_id = mapping.get("db_id") or info.db_id
                info.instance_name = mapping.get("instance") or info.instance_name
                info.instance_number = mapping.get("inst_num") or info.instance_number
                info.release = mapping.get("release") or info.release
                info.rac = mapping.get("rac") or info.rac
        if "host_name" in headers and "platform" in headers:
            data_row = table.find_all("tr")[1] if len(table.find_all("tr")) > 1 else None
            if data_row:
                cells = _row_cells(data_row)
                mapping = dict(zip(headers, cells))
                info.host_name = mapping.get("host_name") or info.host_name
                info.platform = mapping.get("platform") or info.platform
                info.cpus = _to_float(mapping.get("cpus")) or info.cpus
                info.cores = _to_float(mapping.get("cores")) or info.cores
                info.sockets = _to_float(mapping.get("sockets")) or info.sockets
                mem_key = next((k for k in mapping if k.startswith("memory")), None)
                if mem_key:
                    info.memory_gb = _to_float(mapping.get(mem_key)) or info.memory_gb

    for row in soup.find_all("tr"):
        cells = _row_cells(row)
        if not cells:
            continue
        label = cells[0].lower()
        if label.startswith("begin snap"):
            if len(cells) > 1:
                info.begin_snap_id = cells[1]
            if len(cells) > 2:
                info.begin_snap_time = cells[2]
        elif label.startswith("end snap"):
            if len(cells) > 1:
                info.end_snap_id = cells[1]
            if len(cells) > 2:
                info.end_snap_time = cells[2]


def _parse_load_profile(table: Tag, report: AWRReport) -> None:
    rows = table.find_all("tr")
    if not rows:
        return
    header_cells = [_key(c) for c in _row_cells(rows[0])]
    # First header cell is usually empty (label column).
    col_names = header_cells[1:] if header_cells else []
    if not col_names:
        col_names = ["per_second", "per_transaction", "per_exec", "per_call"]

    for row in rows[1:]:
        cells = _row_cells(row)
        if len(cells) < 2:
            continue
        label = _key(cells[0])
        if not label:
            continue
        values = {}
        for i, col in enumerate(col_names, start=1):
            if i < len(cells):
                values[col or f"col{i}"] = _to_float(cells[i])
        report.load_profile[label] = values


def _parse_instance_efficiency(table: Tag, report: AWRReport) -> None:
    for row in table.find_all("tr"):
        cells = _row_cells(row)
        # Cells come in (label, value) pairs, possibly two pairs per row.
        for i in range(0, len(cells) - 1, 2):
            label = cells[i]
            value = cells[i + 1]
            if not label or ":" not in label and "%" not in label:
                continue
            key = _key(label)
            val = _to_float(value)
            if key and val is not None:
                report.instance_efficiency[key] = val


def _parse_wait_events(table: Tag, target: list, class_col_is_name: bool = False) -> None:
    rows = table.find_all("tr")
    if not rows:
        return
    headers = [_norm(c) for c in _row_cells(rows[0])]
    if not headers:
        return
    idx_event = _header_index(headers, r"^event$", r"^wait class$" if class_col_is_name else r"^event$")
    idx_waits = _header_index(headers, r"^waits$")
    idx_time = _header_index(headers, r"total wait time", r"^time\s*\(s\)$", r"^time\(s\)$")
    idx_avg = _header_index(headers, r"avg wait", r"wait avg")
    idx_pct = _header_index(headers, r"% *db *time", r"% *total call time", r"%total")
    idx_class = _header_index(headers, r"wait class")

    if idx_event is None:
        idx_event = 0

    for row in rows[1:]:
        cells = _row_cells(row)
        if not cells or idx_event >= len(cells):
            continue
        name = cells[idx_event]
        if not name or name.lower().startswith("total") or set(name) <= {"-"}:
            continue
        we = WaitEvent(
            event=name,
            waits=_to_float(cells[idx_waits]) if idx_waits is not None and idx_waits < len(cells) else None,
            total_wait_time_sec=_to_float(cells[idx_time]) if idx_time is not None and idx_time < len(cells) else None,
            avg_wait_ms=_to_float(cells[idx_avg]) if idx_avg is not None and idx_avg < len(cells) else None,
            pct_db_time=_to_float(cells[idx_pct]) if idx_pct is not None and idx_pct < len(cells) else None,
            wait_class=cells[idx_class] if idx_class is not None and idx_class < len(cells) else None,
        )
        target.append(we)


def _parse_time_model(table: Tag, report: AWRReport) -> None:
    rows = table.find_all("tr")
    if not rows:
        return
    headers = [_norm(c) for c in _row_cells(rows[0])]
    idx_name = _header_index(headers, r"stat name", r"statistic") or 0
    idx_time = _header_index(headers, r"time \(s\)|time\(s\)")
    idx_pct = _header_index(headers, r"% of db time|%.*db.*time")

    for row in rows[1:]:
        cells = _row_cells(row)
        if not cells or idx_name >= len(cells):
            continue
        name = cells[idx_name]
        if not name:
            continue
        report.time_model[_key(name)] = {
            "time_s": _to_float(cells[idx_time]) if idx_time is not None and idx_time < len(cells) else None,
            "pct_db_time": _to_float(cells[idx_pct]) if idx_pct is not None and idx_pct < len(cells) else None,
        }


def _parse_kv_table(table: Tag, target: dict) -> None:
    rows = table.find_all("tr")
    if not rows:
        return
    headers = [_key(c) for c in _row_cells(rows[0])]
    if len(rows) < 2:
        return
    data = _row_cells(rows[1])
    for h, v in zip(headers, data):
        if h:
            target[h] = _to_float(v) if _to_float(v) is not None else v


def _parse_sql_table(table: Tag, target: list) -> None:
    rows = table.find_all("tr")
    if not rows:
        return
    headers = [_norm(c) for c in _row_cells(rows[0])]
    if not headers:
        return

    idx_value = _header_index(
        headers,
        r"elapsed time \(s\)", r"cpu time \(s\)", r"^gets$", r"buffer gets", r"^reads$",
        r"physical reads", r"^executions$",
    )
    idx_exec = _header_index(headers, r"^executions$")
    idx_per_exec = _header_index(headers, r"per exec")
    idx_pct = _header_index(headers, r"%total", r"% *total", r"%cpu", r"% *db *time")
    idx_sqlid = _header_index(headers, r"sql ?id")
    idx_module = _header_index(headers, r"module")
    idx_text = _header_index(headers, r"sql text|text")

    for row in rows[1:]:
        cells = _row_cells(row)
        if not cells:
            continue
        sql_id = None
        if idx_sqlid is not None and idx_sqlid < len(cells):
            sql_id = cells[idx_sqlid]
        if not sql_id:
            sql_id = next((c for c in cells if _SQL_ID_RE.match(c)), None)
        if not sql_id:
            continue
        stat = SQLStat(
            sql_id=sql_id,
            value=_to_float(cells[idx_value]) if idx_value is not None and idx_value < len(cells) else None,
            executions=_to_float(cells[idx_exec]) if idx_exec is not None and idx_exec < len(cells) else None,
            per_exec=_to_float(cells[idx_per_exec]) if idx_per_exec is not None and idx_per_exec < len(cells) else None,
            pct_total=_to_float(cells[idx_pct]) if idx_pct is not None and idx_pct < len(cells) else None,
            module=cells[idx_module] if idx_module is not None and idx_module < len(cells) else None,
            sql_text=cells[idx_text] if idx_text is not None and idx_text < len(cells) else None,
        )
        target.append(stat)


def _parse_tablespace_io(table: Tag, target: list) -> None:
    rows = table.find_all("tr")
    if not rows:
        return
    headers = [_norm(c) for c in _row_cells(rows[0])]
    idx_ts = _header_index(headers, r"tablespace") or 0
    idx_reads = _header_index(headers, r"^reads$")
    idx_avg_reads = _header_index(headers, r"av reads/s|reads/s")
    idx_avg_rd_ms = _header_index(headers, r"av rd\(ms\)|rd\(ms\)")
    idx_writes = _header_index(headers, r"^writes$")
    idx_avg_writes = _header_index(headers, r"av writes/s|writes/s")
    idx_buf_wait = _header_index(headers, r"buf wt\(ms\)|buffer wait")

    for row in rows[1:]:
        cells = _row_cells(row)
        if not cells or idx_ts >= len(cells):
            continue
        name = cells[idx_ts]
        if not name:
            continue
        target.append(TablespaceIOStat(
            tablespace=name,
            reads=_to_float(cells[idx_reads]) if idx_reads is not None and idx_reads < len(cells) else None,
            avg_reads_per_sec=_to_float(cells[idx_avg_reads]) if idx_avg_reads is not None and idx_avg_reads < len(cells) else None,
            avg_read_time_ms=_to_float(cells[idx_avg_rd_ms]) if idx_avg_rd_ms is not None and idx_avg_rd_ms < len(cells) else None,
            writes=_to_float(cells[idx_writes]) if idx_writes is not None and idx_writes < len(cells) else None,
            avg_writes_per_sec=_to_float(cells[idx_avg_writes]) if idx_avg_writes is not None and idx_avg_writes < len(cells) else None,
            avg_buffer_wait_ms=_to_float(cells[idx_buf_wait]) if idx_buf_wait is not None and idx_buf_wait < len(cells) else None,
        ))
